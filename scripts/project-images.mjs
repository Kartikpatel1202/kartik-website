/**
 * Builds optimised site images.
 *
 *   node scripts/project-images.mjs
 *
 * Reads the originals and writes responsive WebP files (alpha is kept) plus a typed manifest with
 * dimensions and a tiny blurred placeholder to src/content/projectImages.generated.ts:
 * - assets/projects/<slug>/*.png: screenshots copied from each project's own repository
 *   (docs/CONTENT.md §5) → public/images/projects/<slug>/<name>-<width>.webp, id "<slug>/<name>"
 * - assets/portrait/*.png: crops of Kartik's portrait (originals in assets/portrait/source/,
 *   background removed locally) → public/images/portrait/<name>-<width>.webp, id "portrait/<name>"
 * - assets/logos/*.png: square organisation and issuer logos for the work-history, education and
 *   certification cards, cropped from logos
 *   Kartik supplied (2026-11-18) → public/images/logos/<name>-<width>.webp, id "logos/<name>"
 */
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const groups = [
  { source: "assets/projects", nested: true, url: "/images/projects" },
  { source: "assets/portrait", nested: false, url: "/images/portrait", idPrefix: "portrait" },
  // Logos render at 56px, so two small widths (1x and 2x+) are enough.
  {
    source: "assets/logos",
    nested: false,
    url: "/images/logos",
    idPrefix: "logos",
    widths: [128, 256],
  },
];
const manifestPath = path.join(root, "src/content/projectImages.generated.ts");

const WIDE_WIDTHS = [640, 960, 1440, 1920];
const NARROW_WIDTHS = [390, 780];
const QUALITY = 78;

const entries = [];

/** Writes every width of one source image and records its manifest entry. */
async function processImage(input, outDir, url, id, fixedWidths) {
  const name = path.basename(input, ".png");
  const { width, height } = await sharp(input).metadata();
  const candidates = fixedWidths ?? (width >= 1200 ? WIDE_WIDTHS : NARROW_WIDTHS);
  const widths = candidates.filter((w) => w <= width);
  // Always offer the full source width too (up to the largest candidate).
  if (widths.at(-1) !== width && width <= WIDE_WIDTHS.at(-1)) widths.push(width);

  const sources = [];
  for (const w of widths) {
    const outName = `${name}-${w}.webp`;
    await sharp(input)
      .resize({ width: w })
      .webp({ quality: QUALITY, effort: 6 })
      .toFile(path.join(outDir, outName));
    sources.push({ src: `${url}/${outName}`, width: w });
  }

  const blurBuffer = await sharp(input).resize({ width: 16 }).webp({ quality: 40 }).toBuffer();
  entries.push({
    id,
    width,
    height,
    blur: `data:image/webp;base64,${blurBuffer.toString("base64")}`,
    sources,
  });
}

const pngsIn = async (dir) =>
  (await readdir(dir, { withFileTypes: true }))
    .filter((e) => e.isFile() && e.name.endsWith(".png"))
    .map((e) => e.name)
    .sort();

for (const group of groups) {
  const sourceDir = path.join(root, group.source);
  const outRoot = path.join(root, "public", group.url);
  await rm(outRoot, { recursive: true, force: true });

  if (group.nested) {
    for (const slug of (await readdir(sourceDir)).sort()) {
      await mkdir(path.join(outRoot, slug), { recursive: true });
      for (const file of await pngsIn(path.join(sourceDir, slug))) {
        const id = `${slug}/${path.basename(file, ".png")}`;
        await processImage(
          path.join(sourceDir, slug, file),
          path.join(outRoot, slug),
          `${group.url}/${slug}`,
          id,
        );
      }
    }
  } else {
    await mkdir(outRoot, { recursive: true });
    for (const file of await pngsIn(sourceDir)) {
      const id = `${group.idPrefix}/${path.basename(file, ".png")}`;
      await processImage(path.join(sourceDir, file), outRoot, group.url, id, group.widths);
    }
  }
}

const body = entries
  .map(
    (e) =>
      `  ${JSON.stringify(e.id)}: {\n    width: ${e.width},\n    height: ${e.height},\n    blur: ${JSON.stringify(e.blur)},\n    sources: [\n${e.sources
        .map((s) => `      { src: ${JSON.stringify(s.src)}, width: ${s.width} },`)
        .join("\n")}\n    ],\n  },`,
  )
  .join("\n");

await writeFile(
  manifestPath,
  `// Generated by scripts/project-images.mjs. Do not edit by hand.\n\nexport const projectImages = {\n${body}\n} as const;\n\nexport type ProjectImageId = keyof typeof projectImages;\n`,
);

console.log(`Wrote ${entries.length} images to public/images and the manifest.`);
